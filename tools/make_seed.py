#!/usr/bin/env python3
"""Build supabase/seed.sql from the two exported CSVs.
usage: make_seed.py Failed_Startups.csv Founders.csv > supabase/seed.sql"""
import csv,re,sys
INR=85.0  # rupees per US dollar, used once at import time
def usd(s):
    s=(s or '').strip()
    if not s or re.search(r'not publicly|n/?a|unknown',s,re.I): return None
    t=s.lower().replace(',','')
    nums=re.findall(r'(\d+(?:\.\d+)?)',t)
    if not nums: return None
    n=[float(x) for x in nums]
    v=sum(n[:2])/2 if re.search(r'\d\s*-\s*\d',t) else n[0]
    if 'crore' in t or re.search(r'\bcr\b',t): return round(v*1e7/INR)
    if 'lakh' in t or re.search(r'\blac\b',t): return round(v*1e5/INR)
    inr=('₹' in s) or t.startswith('inr') or 'rs' in t.split()
    m=1
    um=re.search(r'\d\s*(billion|bn|b|million|mn|mm|m|thousand|k)\b',t)
    if um:
        u=um.group(1);m=1e9 if u in('billion','bn','b') else 1e6 if u in('million','mn','mm','m') else 1e3
    val=v*m
    return round(val/INR) if inr else round(val)
def q(v):
    if v is None or v=='': return 'null'
    return "'"+str(v).replace("'","''")+"'"
def intval(v):
    m=re.search(r'(19|20)\d\d',v or '');return m.group(0) if m else 'null'
def arr(items):
    if not items: return "'{}'"
    return "array["+",".join(q(i) for i in items)+"]"
def split_names(s):
    out=[]
    for p in re.split(r',|;|\band\b|&|\n',s or ''):
        p=p.strip()
        if p and not re.search(r'not (publicly|found|available)|leadership|team|unknown|n/a',p,re.I): out.append(p)
    return out
def clean(v):
    v=(v or '').strip()
    return '' if v in ('-','Not publicly available','Not Found') else v
def slug_ok(name,url):
    u=url.lower();toks=[t for t in re.findall(r'[a-z]+',name.lower()) if len(t)>=4]
    return any(t in u for t in toks)
rows=list(csv.DictReader(open(sys.argv[1],encoding='utf-8')))
out=["-- Generated by tools/make_seed.py. Safe to re-run: existing startups (same name) are skipped.","begin;"]
total=0;nopar=0;allf={}
for r in rows:
    name=r['Startup Name'].strip()
    if not name: continue
    pub=r['Visible'].strip().lower()=='yes'
    f=usd(r['Funding Amount']);total+=f or 0
    if pub and r['Funding Amount'].strip() and f is None and 'not publicly' not in r['Funding Amount'].lower(): nopar+=1
    fs=split_names(r['Founders'])
    for n in fs: allf.setdefault(n,'')
    tags=[t.strip() for t in re.split(r',',r['Tags']) if t.strip()]
    cols=dict(name=q(name),tagline=q(clean(r['Tagline / Description'])),headquarters=q(clean(r['Headquarters'])),
      founded_year=intval(r['Founded In']),shutdown_year=intval(r['Shutdown Year']),
      funding_amount=q(clean(r['Funding Amount'])),funding_usd=str(f) if f is not None else 'null',
      funding_stage=q(clean(r['Funding stage'])),business_model=q(clean(r['Business Model'])),founders=arr(fs),
      sector=q(clean(r['Sector'])),team_size=q(clean(r['Team Size'])),competitors=q(clean(r['Primary Competition'])),
      key_investors=q(clean(r['Key Investors'])),user_base=q(clean(r['User Base'])),logo_url=q(clean(r['Logo URL'])),
      website_url=q(clean(r['Website URL'])),status_text=q(clean(r['Status']) or ('Failed' if pub else '')),tags=arr(tags),
      underlying_tech=q(clean(r['Underlying Tech'])),failure_reason=q(clean(r['Failure Reason'])),
      epitaph=q(clean(r['Epitaph / Key Lesson'])),postmortem_url=q(clean(r['Post-Mortem URL'])),
      status=q('published' if pub else 'lead'),added_by=q('import' if pub else 'competitor'))
    out.append("insert into public.startups (%s) values (%s) on conflict (name_key) do nothing;"%(",".join(cols),",".join(cols.values())))
# founders directory (LinkedIn only when the link plausibly belongs to that person; the old tab was misaligned)
for r in csv.DictReader(open(sys.argv[2],encoding='utf-8')):
    n=r['Founder Name'].strip();u=r['LinkedIn URL'].strip()
    if n in allf and u.startswith('http') and slug_ok(n,u): allf[n]=u
for n,u in allf.items():
    out.append("insert into public.founders (name,linkedin_url) values (%s,%s) on conflict (name) do update set linkedin_url=coalesce(public.founders.linkedin_url,excluded.linkedin_url);"%(q(n),q(u or None)))
out.append("commit;")
sys.stdout.write("\n".join(out)+"\n")
pub=[r for r in rows if r['Visible'].strip().lower()=='yes']
sys.stderr.write("rows %d published %d leads %d; funding total $%.1fM; unparsed %d; founders %d (%d with linkedin)\n"%(len(rows),len(pub),len(rows)-len(pub),sum(usd(r['Funding Amount']) or 0 for r in pub)/1e6,nopar,len(allf),sum(1 for u in allf.values() if u)))

#!/usr/bin/env python3
"""Joins sheet-control/apps-script/*.gs into ONE file for people who prefer a single paste.
usage (from the repo root):  python3 tools/build-all-in-one.py
Edit the small files in apps-script/, then run this again to refresh the all-in-one copy."""
import glob,os
files=sorted(glob.glob('sheet-control/apps-script/*.gs'))
out='/* GENERATED by tools/build-all-in-one.py from sheet-control/apps-script/. Do not edit this file; edit the small files. */\n\n'
for f in files: out+='/* ====================== '+os.path.basename(f)+' ====================== */\n'+open(f,encoding='utf-8').read().rstrip()+'\n\n'
open('sheet-control/SheetSync-all-in-one.gs','w',encoding='utf-8').write(out)
print('wrote sheet-control/SheetSync-all-in-one.gs from',len(files),'files')
